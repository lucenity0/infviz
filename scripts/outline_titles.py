"""Turn a few FIXED titles into vector outlines of the licensed display face.

    cd engine && uv run --with fonttools --with brotli --with uharfbuzz \
        python ../scripts/outline_titles.py

Reads web/public/fonts/licensed/brutal-milk-var.woff2 (git-ignored; only on a machine that
holds a licence) and writes web/src/outlines.ts: one SVG path per whole string. No font
file, glyph table or per-letter shape is shipped, so the face cannot be used to set new
text; the site shows these words as images and everything else in Inter Tight.
"""
from __future__ import annotations

import io
import json
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "web" / "public" / "fonts" / "licensed" / "brutal-milk-var.woff2"
OUT = ROOT / "web" / "src" / "outlines.ts"

# (text as displayed, weight, letter-spacing in em): must match the CSS that would set it
PANEL = (600, 0.12)  # .head .title: 600, uppercase, var(--track) = 0.12em
STRINGS = [
    ("infviz", 600, 0.01),  # .strip .brand b
    ("KV CACHE", *PANEL),
    ("SPECULATIVE DECODING", *PANEL),
    ("TIMELINE", *PANEL),
    ("ENGINE", *PANEL),
    ("A AGAINST B", *PANEL),
    ("WALL CLOCK", *PANEL),
]


def outline(font_bytes: bytes, text: str, wght: int, track: float) -> dict:
    tt = instantiateVariableFont(TTFont(io.BytesIO(font_bytes)), {"wght": wght})
    buf = io.BytesIO()
    tt.flavor = None
    tt.save(buf)
    data = buf.getvalue()
    upm = tt["head"].unitsPerEm
    asc, desc = tt["hhea"].ascent, -tt["hhea"].descent

    face = hb.Face(data)
    hbfont = hb.Font(face)
    b = hb.Buffer()
    b.add_str(text)
    b.guess_segment_properties()
    hb.shape(hbfont, b, {"kern": True, "liga": False})

    names = tt.getGlyphOrder()
    gs = tt.getGlyphSet()
    pen = SVGPathPen(gs, ntos=lambda v: f"{v:.0f}" if v == int(v) else f"{v:.1f}")
    x = 0.0
    n = len(b.glyph_infos)
    for i, (info, pos) in enumerate(zip(b.glyph_infos, b.glyph_positions)):
        gs[names[info.codepoint]].draw(TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, -pos.y_offset)))
        x += pos.x_advance + (track * upm if i < n - 1 else 0)
    return {"w": round(x), "asc": asc, "h": asc + desc, "upm": upm, "d": pen.getCommands()}


def main() -> None:
    if not FONT.exists():
        raise SystemExit(f"{FONT} not found: the outlines can only be regenerated where the licensed font is")
    raw = TTFont(str(FONT))
    raw.flavor = None
    buf = io.BytesIO()
    raw.save(buf)
    font_bytes = buf.getvalue()
    out = {text: outline(font_bytes, text, w, t) for text, w, t in STRINGS}
    body = json.dumps(out, separators=(",", ":"))
    OUT.write_text(
        "// GENERATED by scripts/outline_titles.py. Do not edit.\n"
        "// Vector outlines of fixed titles in Brutal Milk No 3 (Envato licence; not covered by\n"
        "// this repository's MIT licence). Whole words only: no font file or glyph set ships.\n"
        "export interface Outline { w: number; asc: number; h: number; upm: number; d: string }\n"
        f"export const OUTLINES: Record<string, Outline> = {body};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out)} strings, {len(body) / 1024:.1f} KB")


if __name__ == "__main__":
    main()
